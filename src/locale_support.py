def ui(text: str, lang: str) -> str:
    return UI_FA.get(text,text) if lang == 'fa' else text

def error_summary(exc: Exception, lang: str) -> str:
    raw=str(exc)
    if lang!='fa':return raw
    for pattern, message in ERROR_FA:
        if re.search(pattern,raw,re.I):return message
    return 'عملیات انجام نشد. جزئیات فنی در بخش «نمایش جزئیات» قابل مشاهده است.'

def runtime_message(text: str, lang: str) -> str:
    """Translate common context-sensitive dialogs; preserve identifiers in detail pane."""
    if lang != 'fa':return text
    translated=ui(text,lang)
    if translated != text:return translated
    lowered=text.casefold()
    if ('permanently' in lowered or 'delete' in lowered or 'drop' in lowered) and ('?' in text or 'cannot be undone' in lowered):
        return 'آیا از حذف دائمی مورد انتخاب‌شده اطمینان دارید؟ این عملیات قابل بازگشت نیست.'
    if 'overwrite' in lowered or 'replace existing' in lowered:
        return 'فایل موجود بازنویسی شود؟'
    if 'script' in lowered and 'execute' in lowered:
        return 'آیا می‌خواهید اسکریپت را پس از بررسی اجرا کنید؟ برخی دستورها می‌توانند اطلاعات پایگاه داده را تغییر دهند.'
    if 'constraint' in lowered or 'not found' in lowered or 'no such' in lowered or 'invalid' in lowered:
        return error_summary(ValueError(text),'fa')
    if 'select a' in lowered or 'choose a' in lowered:
        return 'ابتدا گزینه یا رکورد موردنظر را انتخاب کنید.'
    if 'nothing' in lowered or 'no tables' in lowered:
        return 'موردی برای نمایش یا انجام عملیات وجود ندارد.'
    if 'success' in lowered or 'complete' in lowered:
        return 'عملیات با موفقیت انجام شد.'
    return text
